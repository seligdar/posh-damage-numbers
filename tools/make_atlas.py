"""Render the Damage Numbers glyph atlas (white fill, dark outline, soft shadow) and its Lua metrics.

Usage: python make_atlas.py <font.ttf> <out_dir>
The fill is a light vertical gradient so the in-game colour tint keeps a sense of depth;
the outline and shadow are near black, so tinting leaves them dark.
"""
import sys
from dataclasses import dataclass
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont

ATLAS_W, ATLAS_H = 1024, 512
PAD = 6


@dataclass
class Style:
    size: int
    stroke: int
    shadow_dx: int
    shadow_dy: int
    shadow_blur: float


DIGITS = Style(size=78, stroke=7, shadow_dx=3, shadow_dy=5, shadow_blur=3.0)
WORDS = Style(size=46, stroke=5, shadow_dx=2, shadow_dy=4, shadow_blur=2.5)
OUTLINE = (24, 14, 8)


def render(text: str, font: ImageFont.FreeTypeFont, st: Style) -> Image.Image:
    """One glyph/word on a transparent canvas, cropped horizontally, fixed band vertically."""
    asc, desc = font.getmetrics()
    margin = st.stroke + st.shadow_blur * 3 + max(st.shadow_dx, st.shadow_dy) + PAD
    m = int(margin)
    w = int(font.getlength(text)) + 2 * m
    h = asc + desc + 2 * m
    origin = (m, m)

    stroke_mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(stroke_mask).text(origin, text, font=font, fill=255, stroke_width=st.stroke, stroke_fill=255)
    fill_mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(fill_mask).text(origin, text, font=font, fill=255)

    shadow = stroke_mask.filter(ImageFilter.GaussianBlur(st.shadow_blur))
    shadow = ImageChops.offset(shadow, st.shadow_dx, st.shadow_dy).point(lambda v: int(v * 0.6))

    # vertical gradient for the fill: bright top, slightly darker bottom
    top, bottom = m + int(asc * 0.18), m + asc
    grad = Image.new("L", (1, h))
    for y in range(h):
        t = min(1.0, max(0.0, (y - top) / max(1, bottom - top)))
        grad.putpixel((0, y), int(255 - 62 * t))
    grad = grad.resize((w, h))
    # thin bright rim on the upper edge of the fill
    rim = ImageChops.subtract(fill_mask, ImageChops.offset(fill_mask, 0, 3)).point(lambda v: int(v * 0.35))
    fill_rgb = Image.merge("RGB", [ImageChops.add(grad, rim)] * 3)

    out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    out = Image.alpha_composite(out, Image.merge("RGBA", [Image.new("L", (w, h), 0)] * 3 + [shadow]))
    outline_layer = Image.new("RGBA", (w, h), OUTLINE + (0,))
    outline_layer.putalpha(stroke_mask)
    out = Image.alpha_composite(out, outline_layer)
    fill_layer = fill_rgb.convert("RGBA")
    fill_layer.putalpha(fill_mask)
    out = Image.alpha_composite(out, fill_layer)

    xs = [x for x in range(w) if out.crop((x, 0, x + 1, h)).getextrema()[3][1] > 0]
    return out.crop((max(0, xs[0] - 1), 0, min(w, xs[-1] + 2), h))


def main() -> None:
    font_path, out_dir = Path(sys.argv[1]), Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)
    fd = ImageFont.truetype(str(font_path), DIGITS.size)
    fw = ImageFont.truetype(str(font_path), WORDS.size)
    atlas = Image.new("RGBA", (ATLAS_W, ATLAS_H), (0, 0, 0, 0))
    entries: list[tuple[str, int, int, int, int, int]] = []  # key, x, y, w, h, overlap
    x, y, row_h = 2, 2, 0

    def place(key: str, img: Image.Image, overlap: int) -> None:
        nonlocal x, y, row_h
        if x + img.width + 2 > ATLAS_W:
            x, y, row_h = 2, y + row_h + 2, 0
        if y + img.height > ATLAS_H:
            raise RuntimeError(f"atlas too small for {key!r}")
        atlas.paste(img, (x, y))
        entries.append((key, x, y, img.width, img.height, overlap))
        x += img.width + 2
        row_h = max(row_h, img.height)

    def band(images: list[Image.Image]) -> list[Image.Image]:
        """Crop a set of images to their common vertical ink band so they share one baseline."""
        boxes = [im.getchannel("A").getbbox() for im in images]
        top = min(b[1] for b in boxes if b) - 1
        bottom = max(b[3] for b in boxes if b) + 1
        return [im.crop((0, max(0, top), im.width, min(im.height, bottom))) for im in images]

    digit_overlap = DIGITS.stroke + 8
    digit_keys = list("0123456789+-")
    for ch, img in zip(digit_keys, band([render(ch, fd, DIGITS) for ch in digit_keys])):
        place(ch, img, digit_overlap)
    x, y, row_h = 2, y + row_h + 2, 0
    words = (("KO", "НОКАУТ"), ("DEAD", "УБИТ"), ("LIMB", "ОТРУБЛЕНО"),
             ("KO_EN", "KNOCKOUT"), ("DEAD_EN", "KILLED"), ("LIMB_EN", "SEVERED"))
    for (key, _), img in zip(words, band([render(w, fw, WORDS) for _, w in words])):
        place(key, img, 0)

    atlas.save(out_dir / "DamageNumbers_atlas.png", optimize=True)
    lines = ["-- generated by make_atlas.py: atlas rectangles in pixels", "return {",
             f"  texture = \"DamageNumbers_atlas.png\", width = {ATLAS_W}, height = {ATLAS_H},", "  glyphs = {"]
    for key, gx, gy, gw, gh, ov in entries:
        lines.append(f"    [\"{key}\"] = {{ x = {gx}, y = {gy}, w = {gw}, h = {gh}, overlap = {ov} }},")
    lines += ["  },", "}", ""]
    (out_dir / "dn_glyphs.lua").write_text("\n".join(lines), encoding="utf-8")
    print(f"atlas rows used up to y={y + row_h}, glyphs={len(entries)}")


if __name__ == "__main__":
    main()
