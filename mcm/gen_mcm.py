"""Settings description of the mod (mcm/spec.py) + texts (lang/*.txt) -> the MCM plugin source (C++) and the Lua
settings module.

ModConfigMenu (MCM) only finds RE_Kenshi plugin DLLs that export MCM_Describe. Our mods are KenshiLua scripts,
so each mod gets a tiny DLL that describes its ini for MCM and counts how many times MCM applied a change;
the script reads the ini at start and again whenever that counter moves.

Texts: lang/en.txt is complete; every other lang/<code>.txt may leave keys out, those get the English text.
<code> is the first two letters of the game language in settings.cfg (language=zh_CN -> zh.txt).

Usage: gen_mcm.py out_dir
"""
import sys
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
from spec import MOD, Item, Mod  # noqa: E402

LANG_DIR = HERE.parent / "lang"
FONT_CANNOT_DRAW = "—–«»…№"         # MCM draws with the game's fonts, these characters come out as boxes


@dataclass
class Lang:
    code: str
    texts: dict[str, str]


def read_lang(path: Path) -> Lang:
    """key = text per line; # starts a comment line."""
    texts: dict[str, str] = {}
    for n, raw in enumerate(path.read_text(encoding="utf-8-sig").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if " = " not in line:
            raise ValueError(f"{path.name}:{n}: expected 'key = text', got {raw!r}")
        key, text = line.split(" = ", 1)
        key = key.strip()
        if key in texts:
            raise ValueError(f"{path.name}:{n}: {key} is given twice")
        for bad in FONT_CANNOT_DRAW:
            if bad in text:
                raise ValueError(f"{path.name}:{n}: MCM fonts cannot draw {bad!r} in {key}")
        texts[key] = text.strip()
    return Lang(path.stem.lower(), texts)


def text_keys(mod: Mod, english: Lang) -> list[str]:
    """Every text the plugin and the script use, in page order. Tips are optional (only where English has one)."""
    keys = ["info"]
    for s in mod.sections:
        keys.append(f"section.{s.id}")
        for it in s.items:
            keys.append(it.key)
            if f"{it.key}.tip" in english.texts:
                keys.append(f"{it.key}.tip")
            keys.extend(f"{it.key}.{v}" for v in it.values)
    keys.extend(f"script.{k}" for k in mod.script_texts)
    return keys


def load_langs(mod: Mod) -> tuple[list[str], list[Lang]]:
    english = read_lang(LANG_DIR / "en.txt")
    keys = text_keys(mod, english)
    missing = [k for k in keys if k not in english.texts]
    if missing:
        raise ValueError(f"lang/en.txt has no text for: {', '.join(missing)}")
    langs = [english]
    for path in sorted(LANG_DIR.glob("*.txt")):
        if path.stem.lower() == "en":
            continue
        lang = read_lang(path)
        if len(lang.code) != 2:
            raise ValueError(f"{path.name}: the file name must be the two-letter language code, like zh.txt")
        unknown = [k for k in lang.texts if k not in english.texts]
        if unknown:
            raise ValueError(f"{path.name}: unknown keys {', '.join(unknown)}")
        left = [k for k in keys if k not in lang.texts]
        if left:
            print(f"{path.name}: {len(left)} texts not translated yet, English is used: {', '.join(left)}")
        langs.append(Lang(lang.code, {k: lang.texts.get(k, english.texts[k]) for k in keys}))
    return keys, langs


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cpp_for(mod: Mod, keys: list[str], langs: list[Lang]) -> str:
    index = {k: i for i, k in enumerate(keys)}

    def txt(key: str) -> str:
        return f"L({index[key]})"

    rows = []
    for lang in langs:
        rows.append("    {\n" + "".join(f"        {c_str(lang.texts[k])},\n" for k in keys) + "    },")
    out = [
        "// Generated by gen_mcm.py from mcm/spec.py and lang/*.txt; edit those instead.",
        f"// MCM page for {mod.title}: a KenshiLua mod, so this DLL only describes its ini for ModConfigMenu",
        "// and counts how many times MCM applied a change (the script polls Posh_SettingsVersion).",
        "#include <windows.h>",
        "#include <string.h>",
        '#include "ModConfigMenu.h"',
        "",
        "static char g_ini[1024];",
        "static volatile LONG g_version = 1;",
        "static int g_ready = 0;",
        "static int g_lang = 0;",
        "",
        f"#define LANG_COUNT {len(langs)}",
        f"#define TEXT_COUNT {len(keys)}",
        "static const char* const LANGS[LANG_COUNT] = { " + ", ".join(c_str(l.code) for l in langs) + " };",
        "static const char* const TEXTS[LANG_COUNT][TEXT_COUNT] = {",
        *rows,
        "};",
        "#define L(i) (TEXTS[g_lang][i])",
        "",
        "static char Lower(char c) { return (c >= 'A' && c <= 'Z') ? (char)(c - 'A' + 'a') : c; }",
        "",
        "// settings.cfg holds language=zh_CN; the game runs from its own folder. Returns the index in LANGS, 0 is English.",
        "static int GameLanguage(const char* modDir)",
        "{",
        "    char path[1024];",
        "    const char* tries[2] = { \"settings.cfg\", path };",
        "    strcpy_s(path, sizeof(path), modDir);",
        "    strcat_s(path, sizeof(path), \"..\\\\..\\\\settings.cfg\");",
        "    for (int i = 0; i < 2; ++i)",
        "    {",
        "        HANDLE f = CreateFileA(tries[i], GENERIC_READ, FILE_SHARE_READ | FILE_SHARE_WRITE, NULL, OPEN_EXISTING, 0, NULL);",
        "        if (f == INVALID_HANDLE_VALUE) continue;",
        "        char buf[8192];",
        "        DWORD got = 0;",
        "        ReadFile(f, buf, sizeof(buf) - 1, &got, NULL);",
        "        CloseHandle(f);",
        "        buf[got] = 0;",
        "        const char* at = strstr(buf, \"language=\");",
        "        if (at == NULL) return 0;",
        "        for (int l = 0; l < LANG_COUNT; ++l)",
        "            if (Lower(at[9]) == LANGS[l][0] && Lower(at[10]) == LANGS[l][1]) return l;",
        "        return 0;",
        "    }",
        "    return 0;",
        "}",
        "",
        "static void Init()",
        "{",
        "    if (g_ready) return;",
        "    g_ready = 1;",
        "    HMODULE self = NULL;",
        "    GetModuleHandleExA(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT,",
        "                       (LPCSTR)&Init, &self);",
        "    GetModuleFileNameA(self, g_ini, sizeof(g_ini));",
        "    char* slash = strrchr(g_ini, '\\\\');",
        "    if (slash) slash[1] = 0;",
        "    g_lang = GameLanguage(g_ini);",
        f"    strcat_s(g_ini, sizeof(g_ini), {c_str(mod.ini)});",
        "}",
        "",
        "static void __cdecl Apply() { InterlockedIncrement(&g_version); }",
        "",
        "extern \"C\" __declspec(dllexport) const char* Posh_IniPath() { Init(); return g_ini; }",
        "extern \"C\" __declspec(dllexport) int Posh_SettingsVersion() { return (int)g_version; }",
        "",
        "// RE_Kenshi calls startPlugin of every plugin it loads",
        "__declspec(dllexport) void startPlugin() { Init(); }",
        "",
        "extern \"C\" __declspec(dllexport) void MCM_Describe(MCM_Api* api)",
        "{",
        "    Init();",
        f"    const char* sec = {c_str(mod.mod_id)};",
        f"    api->beginMod(api, {c_str(mod.mod_id)}, {c_str(mod.title)}, g_ini, &Apply);",
        f"    if (api->version >= 2) api->info(api, {txt('info')});",
    ]
    for s in mod.sections:
        out.append(f"    api->section(api, {txt(f'section.{s.id}')});")
        for it in s.items:
            label = txt(it.key)
            tip = txt(f"{it.key}.tip") if f"{it.key}.tip" in index else "NULL"
            flags = "MCM_RESTART" if it.restart else "0"
            out.append(item_call(it, label, tip, flags, [txt(f"{it.key}.{v}") for v in it.values]))
    out.append("}")
    return "\n".join(out) + "\n"


def item_call(it: Item, label: str, tip: str, flags: str, value_labels: list[str]) -> str:
    if it.kind == "bool":
        return f"    api->toggle(api, sec, {c_str(it.key)}, {label}, {tip}, {1 if it.default else 0}, {flags});"
    if it.kind == "int":
        return f"    api->integer(api, sec, {c_str(it.key)}, {label}, {tip}, {int(it.default)}, {int(it.lo)}, {int(it.hi)}, {flags});"
    if it.kind == "float":
        return (f"    api->number(api, sec, {c_str(it.key)}, {label}, {tip}, {float(it.default)}f, {float(it.lo)}f, "
                f"{float(it.hi)}f, {it.decimals}, {flags});")
    if it.kind == "choice":
        vals = ", ".join(c_str(v) for v in it.values)
        return "\n".join([
            "    {",
            f"        static const char* const values[] = {{ {vals} }};",
            f"        const char* labels[] = {{ {', '.join(value_labels)} }};",
            f"        api->choice(api, sec, {c_str(it.key)}, {label}, {tip}, {c_str(it.default)}, values, labels, {len(it.values)}, {flags});",
            "    }",
        ])
    if it.kind == "colour":
        return f"    api->colour(api, sec, {c_str(it.key)}, {label}, {tip}, {c_str(it.default)}, {flags});"
    raise ValueError(f"unknown setting kind {it.kind} of {it.key}")


def lua_value(v: object) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return c_str(str(v))


def lua_for(mod: Mod, langs: list[Lang]) -> str:
    items = []
    for s in mod.sections:
        for it in s.items:
            parts = [f'key = "{it.key}"', f'kind = "{it.kind}"', f'root = "{it.root}"',
                     "path = { " + ", ".join(f'"{p}"' for p in it.path) + " }", f"default = {lua_value(it.default)}"]
            if it.kind in ("int", "float"):
                parts.append(f"lo = {it.lo!r}, hi = {it.hi!r}")
            if it.kind == "choice":
                parts.append("values = { " + ", ".join(f'"{v}"' for v in it.values) + " }")
            items.append("        { " + ", ".join(parts) + " },")
    texts = []
    for lang in langs:
        pairs = ", ".join(f"{k} = {c_str(lang.texts['script.' + k])}" for k in mod.script_texts)
        texts.append(f"    {lang.code} = {{ {pairs} }}," if pairs else f"    {lang.code} = {{}},")
    template = (HERE / "settings_template.lua").read_text(encoding="utf-8")
    return (template
            .replace("@MODULE@", mod.lua_module)
            .replace("@SECTION@", mod.mod_id)
            .replace("@DLL@", mod.dll)
            .replace("@INI@", mod.ini)
            .replace("@FOLDER@", mod.folder)
            .replace("@ITEMS@", "\n".join(items))
            .replace("@TEXTS@", "\n".join(texts)))


def main() -> None:
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    keys, langs = load_langs(MOD)
    (out / MOD.dll.replace(".dll", ".cpp")).write_text(cpp_for(MOD, keys, langs), encoding="utf-8")
    (out / (MOD.lua_module + ".lua")).write_text(lua_for(MOD, langs), encoding="utf-8")
    print(MOD.title, sum(len(s.items) for s in MOD.sections), "settings,", len(keys), "texts, languages:",
          " ".join(l.code for l in langs))


if __name__ == "__main__":
    main()
